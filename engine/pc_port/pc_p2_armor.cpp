bool pc_p2_armor_receiver_rejects(Teki* teki, const InteractAttack* attack) {
    if (!ready || !teki) return false;
    auto it = actors.find(static_cast<PelletView*>(teki));
    if (it == actors.end()) return false;
    Armor& s = it->second;
    const unsigned tok = s.token ? s.token : (teki->mGenerator ? teki->mGenerator->_70 : 0u);

    if (s.coll.own && !s.coll.released) {
        // Source Armor::damageCallBack on the retail tree: only `dmg1` (or Bittered) takes damage. A hit that
        // carries a part is a latched Pikmin (the stuck part is its hit part); the shell and the body
        // cannot be stuck to, so they never reach here with a part. A partless hit is refused, except a
        // captain punch whose hand reaches the head sphere (NaviPunchState::hitCallback delivers the part the
        // hand touched; the port punch carries none, so the head reach stands in for it).
        const bool hasPart = attack && attack->mCollPart;
        const unsigned partId = hasPart ? attack->mCollPart->getID().mId : 0u;
        bool accept = p2armor::partAccepts(s.bittered, partId) && (hasPart || s.bittered);
        const char* reason = accept ? (s.bittered ? "bittered" : "dmg1") : "reject";
        const bool navi = attack && attack->mOwner && attack->mOwner->mObjType == OBJTYPE_Navi;
        CollPart* head = s.coll.node[p2armor::NodeDmg1];
        if (!accept && !hasPart && navi && head) {
            Navi* n = static_cast<Navi*>(attack->mOwner);
            const float reach = C_NAVI_PARM(n, mPunchRadius) + n->getCentreSize();
            if (p2armor::punchReachesHead(p2captorhost::vec(n->getPosition()), n->mFaceDirection,
                                          p2captorhost::vec(head->mCentre), head->mRadius, reach)) {
                accept = true;
                reason = "punch_head";
            }
        }
        // Bounded: the first 40 decisions, then every 25th (a latched Pikmin attacks every few frames).
        const int n = ++s.recvLogged;
        if (n <= 40 || n % 25 == 0) {
            std::printf("P2_ARMOR_RECEIVER generator=%u decision=%s reason=%s part=%s navi=%d n=%d\n", tok,
                        accept ? "accept" : "reject", reason,
                        hasPart ? fourCCString(partId).c_str() : "none", int(navi), n);
            std::fflush(stdout);
        }
        return !accept;
    }

    p2armorreceiver::Inputs in;
    in.bittered = s.bittered;
    in.has_part = attack && attack->mCollPart;
    in.part_id = in.has_part ? attack->mCollPart->getID().mId : 0u;
    // Host tree only (PIKMIN_P2_ARMOR_OWN_COLL=0): the port weakpoint substitutes for the missing source
    // `dmg1` part; the exact source rule already covers `dmg1` when present.
    in.weakpoint_active = s.weakpointActive && !s.dmg1Present;
    in.weakpoint_id = s.weakpointId;

    const p2armorreceiver::Decision decision = p2armorreceiver::decide(in);
    const bool reject = decision == p2armorreceiver::Decision::Reject;
    std::printf("P2_ARMOR_RECEIVER generator=%u decision=%s reason=%s part=%s bittered=%d "
                "weakpoint=%s\n",
                tok, reject ? "reject" : "accept",
                p2armorreceiver::decisionName(decision),
                in.has_part ? fourCCString(in.part_id).c_str() : "none", int(in.bittered),
                s.weakpointActive ? fourCCString(s.weakpointId).c_str() : "none");
    std::fflush(stdout);
    return reject;
}
