// One source Obj::attackPikmin pass (default eat condition; the stabbed
// swallow maps to the P1 receiver's Esa motion).
int attackPikmin(BTeki* a, Armor& s, unsigned generator, int frame) {
    // The bite sphere is the source mouth joint (kamujnt, r25) where the drawn jaw is at source frame `frame`
    // of attack2: it rears up, then lunges ahead of the body (Armor.cpp:232-261). No facing test.
    float mouthLocal[1][3] = {{0.0f, 0.0f, 0.0f}};
    p2armor::mouthCentre(p2armor::clipIndex("attack2"), float(frame), mouthLocal[0]);
    for (int k = 0; k < 3; ++k) mouthLocal[0][k] *= s.scale;
    const p2captor::Geometry g{15u, 1, p2armor::MouthRadius, p2armor::PoisonDamage, mouthLocal};
    if (!s.mouthLogged) {
        s.mouthLogged = true;
        std::printf("P2_ARMOR_MOUTH generator=%u slots=%d radius=%.1f source=kamujnt_tables scale=%.2f "
                    "host_slots=%d\n", generator, g.slots, g.radius, double(s.scale), p2captorhost::hostSlotCount(a));
        std::fflush(stdout);
    }
    bool occupied[p2captor::MaxSlots] = {};
    p2captorhost::validate(a, s.held, g.slots, occupied);
    p2captorhost::Scene scene = p2captorhost::snapshot(a);
    const p2captor::Vec3 apos = p2captorhost::vec(a->getPosition());
    int refused = 0;
    const int caught = p2captor::eat(g, apos, s.heading, scene.prey.data(), (int)scene.prey.size(), occupied,
                                     p2captor::defaultEligible, [&](int n, int slot) {
        // motion 1 = Fall (limp): the source stab plays SUWARERU, not the eaten ESA (interactPiki.cpp:675-678)
        if (!p2captorhost::swallowInto(a, scene, n, slot, s.held, 1, &refused)) return false;
        const p2captor::Vec3 l = p2captor::toLocal(apos, s.heading, scene.prey[n].pos);
        const p2armor::Polar pl = p2armor::polar(apos, a->getDirection(), scene.prey[n].pos);
        const float df = drawFrame(s);
        const p2armor::Vec3 src = sourceMouth(a, s, df);
        std::printf("P2_ARMOR_BITE generator=%u frame=%d pikmin=1 slot=%d local_x=%.1f local_y=%.1f local_z=%.1f "
                    "angle_deg=%.1f dist_xz=%.1f draw_frame=%.1f source_mouth_dist=%.1f heading=%.3f direction=%.3f\n",
                    generator, frame, slot, l.x, l.y, l.z, double(pl.angleDeg), double(pl.distXZ), double(df),
                    double(p2chappymouth::distance(src, scene.prey[n].pos)), double(s.heading),
                    double(a->getDirection()));
        std::fflush(stdout);
        if (!s.biteShot) { s.biteShot = true; shot("bite"); }
        return true;
    });
    if (refused > 0) {
        std::printf("P2_ARMOR_EAT_REFUSED generator=%u reason=no_host_slot count=%d\n", generator, refused);
        std::fflush(stdout);
    }
    return caught;
}
void enter(Armor& s, State state, const char* clip) {
    s.state = state;
    s.stateTime = 0.0f;
    s.biteLogged = false;
    if (clip) s.clip = clip;
    auto it = clips.find(s.clip);
    if (it != clips.end()) {
        s.events.start(it->second.sampled, it->second.name);
    } else {
        s.events.cancel();
    }
}
void walkTo(BTeki* a, Armor& s, const Vector3f& target, float dt) {
    const Vector3f pos = a->getPosition();
    const float desired = std::atan2(target.x - pos.x, target.z - pos.z);
    const float frames = dt * 30.0f;  // source frames this tick
    float diff = wrapPi(desired - s.heading) * TURN_SPEED * frames;
    const float maxTurn = TURN_MAX * frames;
    if (diff > maxTurn) diff = maxTurn;
    if (diff < -maxTurn) diff = -maxTurn;
    s.heading = wrapPi(s.heading + diff);
    a->setDirection(s.heading);
    const Vector3f drive(std::sin(s.heading) * MOVE_SPEED, 0.0f,
                         std::cos(s.heading) * MOVE_SPEED);
    a->inputDrive(drive);
    a->mVelocity.set(drive);
}
void stop(BTeki* a) {
    a->inputDrive(Vector3f(0.0f, 0.0f, 0.0f));
    a->mVelocity.x = 0.0f;
    a->mVelocity.y = 0.0f;
    a->mVelocity.z = 0.0f;
}

void setPhase(Armor& s) {
    if (s.state == ARMOR_STAY) { s.phase = 0.0f; return; }
    const float duration = clipDuration(s.clip);
    const float len = duration > 0.0f ? duration : 1.0f;
    if (clipLoops(s.clip)) {
        s.phase = s.stateTime / len;
        s.phase -= std::floor(s.phase);
    } else {
        s.phase = s.stateTime / len;
        if (s.phase > 1.0f) s.phase = 1.0f;
    }
}
