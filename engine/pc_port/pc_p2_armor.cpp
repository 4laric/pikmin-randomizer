// Family-owned ground-invertebrate source behavior for the batch-2 Chappy
// placement vehicle: Cloaking Burrow-nit (Armor, EnemyID 15). Implements the
// source ArmorState.cpp combat FSM: Stay (buried) -> Appear -> Move/GoHome ->
// Attack2 -> Eat/Fail -> Dead, plus Flick. Bridge states (Attack1, MoveSide/
// Centre/Top) are source-backed N/A because the arena has no ItemBridge.
// Source revision 632af93787b9c95b63f0c13be32b161375ce3a96; retail parms from
// experimental/pikmin2_ground_inverts_assets.py (GPVE01 rev 0).
//
// Source truth for the collision and the bite (#1014; decomp citations in pc_p2_armor_policy.h):
//   * Collision tree: the retail armor/enemycoll.txt tree is bound as the actor's own CollInfo (buildColl):
//     root r40 on kosijnt (`____`), `dmg1` r17.5 on headjnt (`st__`) and the shell r22.5 on kourajnt (`_t__`).
//     Only `dmg1` is stickable (CollPart::isStickable, collinfo.cpp:806) and only `dmg1` passes
//     Armor::damageCallBack (Armor.cpp:117-128), so a Pikmin can latch and hurt the head only; the shell
//     (kourajnt) and the body are invincible. The parts are posed every tick from per-frame tables
//     generated by scripts/p2_armor_tables.py (pc_p2_armor_tables.h). The retail ids of root and shell are
//     both `none`; the port names them root/shll so each can be found (nothing keys on them).
//   * Mouth slot: Obj::attackPikmin (Armor.cpp:232-261) runs once per source frame 17 < f < 27 of attack2
//     (ArmorState.cpp:586-589) and stabs every Pikmin whose 3D distance to the kamujnt joint is below 25
//     (there is no facing test). The joint is taken from the tables at that frame: it rears up and then
//     lunges ~150 units ahead of the body. A stabbed Pikmin is stuck to the actor's own 'slot'/'kam1' part,
//     which follows kamujnt, so it rides the drawn jaw through the eat clip; the eat source event (frame 60)
//     runs killSlotPiki = swallowPikmin(fp01 = 300) on Pikmin still held. Attack2 END goes to Eat only while
//     a Pikmin is held (getSlotPikiNum). Death and teardown release the mouth; the port's own flick sweep
//     spares held Pikmin. Eat/flick timing comes from the authoritative sampled clock (#431).
//   * Attack start: isTargetAttackable / getNearestPikminOrNavi with the retail fp20 75 range and fp21 15
//     degree angle (ArmorState.cpp:231, :470); the turn toward the target follows the source law (10% of the
//     angle error per source frame, capped at 10 degrees: fp08 / fp28). attack2 frame 22 runs attackNavi
//     (fp22 75, fp23 15, fp24 10 damage).
//   * Damage paths: a latched Pikmin attack carries the stuck part, so only `dmg1` takes it; a partless
//     Pikmin punch is refused; a captain punch is accepted only when the hand reaches the head sphere
//     (NaviPunchState::hitCallback delivers the part the hand touched); a bomb takes the base
//     EnemyBase::bombCallBack (addDamage on any part, the Armor does not override it). The source
//     hipdropCallBack (purple) follows the same `dmg1` rule; the port has no part-carrying hipdrop.
//
// Port adaptations (recorded, not retail-faithful):
//   * The tree is swapped onto the P1 Chappy host (like the Bloyster and the Emperor); the host tree comes
//     back at death (carcass/centre seated on the body) and at stage teardown. PIKMIN_P2_ARMOR_OWN_COLL=0
//     keeps the host tree for A/B evidence (the receiver then falls back to the legacy weakpoint rule).
//   * `EB_Bittered` has no P1 host equivalent; pc_p2_armor_set_bittered is the
//     explicit host/fixture input for the bittered leg of the same rule.
//   * `doStartStoneState` flick is implemented, but the P1 host has no
//     petrification lifecycle. pc_p2_armor_update fires it on the rising edge
//     of TEKIOPT_Pressed (the host's flattened/incapacitated analogue) and the
//     port records `P2_ARMOR_STONE_NOTE host_lifecycle=absent port_analogue=pressed`.
//   * View angle is a full hemisphere (fp13 absent from the Armor general block);
//     the flick radius is a documented port adaptation.
// No other lane's module is modified; every hook is a no-op for unregistered actors.
