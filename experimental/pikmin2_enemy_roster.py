def _split_top_level(text: str) -> list[str]:
    """Split ``text`` on commas outside quoted strings and parentheses."""
    fields: list[str] = []
    current: list[str] = []
    depth = 0
    in_string = False
    escaped = False
    for char in text:
        if in_string:
            current.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
            current.append(char)
        elif char == "(":
            depth += 1
            current.append(char)
        elif char == ")":
            depth -= 1
            current.append(char)
        elif char == "," and depth == 0:
            fields.append("".join(current).strip())
            current = []
        else:
            current.append(char)
    tail = "".join(current).strip()
    if tail:
        fields.append(tail)
    return fields


def parse_enum_header(text: str) -> dict[str, dict]:
    import re
    pattern = re.compile(r"^\s*EnemyID_(\w+)\s*=\s*(-?\d+)\s*,\s*//\s*(.*?)\s*$")
    records: dict[str, dict] = {}
    for line in text.splitlines():
        match = pattern.match(line)
        if not match:
            continue
        enum_name, numeric, comment = match.groups()
        records[enum_name] = {
            "source_id": int(numeric),
            "common_name": comment.rstrip(",").strip(),
        }
    return records


def _enum_ref(field_text: str) -> str | None:
    field_text = field_text.strip()
    if field_text in ("-1", ""):
        return None
    if "EnemyID_" in field_text:
        return field_text.rsplit("EnemyID_", 1)[1].strip()
    raise RosterError(f"unexpected enum reference: {field_text!r}")


def _unquote(field_text: str) -> str:
    field_text = field_text.strip()
    if len(field_text) >= 2 and field_text[0] == '"' and field_text[-1] == '"':
        return field_text[1:-1]
    raise RosterError(f"expected string literal, got {field_text!r}")


def parse_info_table(text: str) -> dict[str, dict]:
    start = text.index("gEnemyInfo[]")
    start = text.index("{", start)
    end = text.index("};", start)
    body = text[start + 1:end]
    records: dict[str, dict] = {}
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if not line.startswith("{") or "#" in line:
            continue
        line = line.rstrip(",")
        fields = _split_top_level(line[1:-1])
        if len(fields) < 15:
            continue
        name = _unquote(fields[0])
        enum_name = _enum_ref(fields[1])
        if enum_name is None:
            continue
        parent = _enum_ref(fields[2])
        members = int(fields[3])
        flags_text = fields[4]
        assets = {
            "model": _unquote(fields[5]),
            "anim": _unquote(fields[6]),
            "anim_mgr": _unquote(fields[7]),
            "texture": _unquote(fields[8]),
            "param": _unquote(fields[9]),
            "collision": _unquote(fields[10]),
            "stone": _unquote(fields[11]),
        }
        child = _enum_ref(fields[12])
        child_count = fields[13].strip()
        if child_count in CHILD_COUNT_MACROS:
            child_count = CHILD_COUNT_MACROS[child_count]
        drop_type = fields[14].strip()
        day_end_max = None
        for flag, value in (("EFlag_DayEndMax1", 1), ("EFlag_DayEndMax2", 2), ("EFlag_DayEndMax4", 4)):
            if flag in flags_text:
                day_end_max = value
        records[name] = {
            "enum_name": enum_name,
            "source_name": name,
            "parent_name": parent,
            "members": members,
            "spawnable": "EFlag_CanBeSpawned" in flags_text,
            "use_own_id": "EFlag_UseOwnID" in flags_text,
            "has_no_info": "EFlag_HasNoInfo" in flags_text,
            "day_end_max": day_end_max,
            "drop_type": drop_type,
            "child_name": child,
            "child_count": int(child_count),
            "assets": assets,
        }
    return records


